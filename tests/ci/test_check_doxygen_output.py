#!/usr/bin/env python3
"""Shipping-inventory contracts; synthetic CPP tests the conservative boundary.

HTML producer fixtures are captured from Doxygen, rather than inferred from its
file names. This suite runs with the mandatory doc-class guard.
"""
from __future__ import annotations

import contextlib
import importlib.util
import io
import os
from pathlib import Path
import tempfile
import types
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts/docs/check_doxygen_output.py"
spec = importlib.util.spec_from_file_location("check_doxygen_output", SCRIPT)
assert spec and spec.loader
guard = importlib.util.module_from_spec(spec)
spec.loader.exec_module(guard)

# Captured from docs/api/cpp/html/classGaussianData.html generated by Doxygen
# 1.9.8 with the repository's unchanged docs/Doxyfile. This is the actual title
# line; the surrounding page is unnecessary for this title-only parser.
CAPTURED_CLASS_TITLE = "<title>Godot Gaussian Splatting: GaussianData Class Reference</title>"


class ShippingInventoryTests(unittest.TestCase):
    def test_tests_only_registration_is_omitted(self):
        source = "GDREGISTER_CLASS(Public);\n#ifdef TESTS_ENABLED\nGDREGISTER_CLASS(TestOnly);\n#endif"
        self.assertEqual(guard.expected_classes(source), ["Public"])
        self.assertEqual(guard.expected_classes("GDREGISTER_CLASS(TestOnly);"), ["TestOnly"])

    def test_possible_shipping_branches_remain_required(self):
        for condition in ("defined(TOOLS_ENABLED)", "defined(UNKNOWN)",
                          "defined(TESTS_ENABLED) || defined(UNKNOWN)", "TESTS_ENABLED == 1"):
            with self.subTest(condition=condition):
                source = f"#if {condition}\nGDREGISTER_CLASS(A);\n#else\nGDREGISTER_CLASS(B);\n#endif"
                self.assertEqual(guard.expected_classes(source), ["A", "B"])

    def test_shipping_else_and_ifndef_remain_required(self):
        source = "#ifdef TESTS_ENABLED\nGDREGISTER_CLASS(TestOnly);\n#else\nGDREGISTER_CLASS(Public);\n#endif\n#ifndef TESTS_ENABLED\nGDREGISTER_CLASS(Other);\n#endif"
        self.assertEqual(guard.expected_classes(source), ["Other", "Public"])

    def test_nested_test_branches_cannot_hide_shipping_classes(self):
        source = "#ifdef TOOLS_ENABLED\n#ifdef TESTS_ENABLED\nGDREGISTER_CLASS(TestOnly);\n#endif\nGDREGISTER_CLASS(Public);\n#endif"
        self.assertEqual(guard.expected_classes(source), ["Public"])

    def test_original_namespace_macro_sorting_and_comments_are_preserved(self):
        source = "/* #ifdef TESTS_ENABLED\nGDREGISTER_CLASS(Comment); */\nGDREGISTER_ABSTRACT_RUNTIME_CLASS(NS::Z);\nGDREGISTER_CLASS(A);\nGDREGISTER_CLASS(A); // GDREGISTER_CLASS(Comment)"
        self.assertEqual(guard.expected_classes(source), ["A", "NS::Z"])

    def test_real_shipping_inventory_differs_only_by_tests_only_registration(self):
        source = guard.REGISTER_TYPES.read_text(encoding="utf-8")
        original = set(guard.REGISTER_RE.findall(guard._strip_comments(source)))
        expected = set(guard.expected_classes(source))
        self.assertTrue(expected)
        self.assertEqual(original - expected, {"GSLiveEditorTestRunner"})
        self.assertEqual(expected - original, set())
        self.assertIn("GaussianSplatting::GaussianSceneSerializer", expected)

    def test_every_shipping_page_is_still_required(self):
        expected = guard.expected_classes(guard.REGISTER_TYPES.read_text(encoding="utf-8"))
        self.assertTrue(expected)
        self.assertEqual(guard.check(expected, set(expected)), [])
        for name in expected:
            with self.subTest(name=name):
                self.assertEqual(guard.check(expected, set(expected) - {name}),
                                 [f"{name}: registered in the module but has no Doxygen class page"])

    def test_empty_inventory_and_empty_documentation_fail(self):
        self.assertTrue(guard.check([], set()))
        self.assertTrue(guard.check(["Public"], set()))

    def test_malformed_nesting_fails(self):
        for source in ("#endif", "#ifdef TESTS_ENABLED", "#else", "#if UNKNOWN\n#else\n#elif UNKNOWN\n#endif"):
            with self.subTest(source=source), self.assertRaises(ValueError):
                guard.expected_classes(source)

    def test_missing_projector_fails(self):
        with tempfile.TemporaryDirectory() as tmp, \
                mock.patch.object(guard, "SHIPPING_PROJECTION", Path(tmp) / "missing.py"), \
                self.assertRaises(RuntimeError):
            guard.expected_classes("GDREGISTER_CLASS(Public);")

    def test_unloadable_projector_fails(self):
        with mock.patch.object(guard.importlib.util, "spec_from_file_location", return_value=None), \
                self.assertRaises(RuntimeError):
            guard.expected_classes("GDREGISTER_CLASS(Public);")

    def test_invalid_projector_module_fails(self):
        for module in (types.SimpleNamespace(), types.SimpleNamespace(_shipping_registration_source=42),
                       types.SimpleNamespace(_shipping_registration_source=lambda text: None)):
            with self.subTest(module=module), \
                    mock.patch.object(guard.importlib.util, "module_from_spec", return_value=module), \
                    mock.patch("importlib.machinery.SourceFileLoader.exec_module"), \
                    self.assertRaises(RuntimeError):
                guard.expected_classes("GDREGISTER_CLASS(Public);")

    def test_main_reports_bad_registration_source_without_fallback(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "register_types.cpp"
            for data in (b"#ifdef TESTS_ENABLED\nGDREGISTER_CLASS(Public);", b"\xff"):
                source.write_bytes(data)
                with self.subTest(data=data), mock.patch.object(guard, "REGISTER_TYPES", source), \
                        mock.patch.object(guard, "documented_classes") as documented, \
                        contextlib.redirect_stderr(io.StringIO()) as error:
                    self.assertEqual(guard.main(["--html-dir", tmp]), 1)
                    self.assertIn("ERROR:", error.getvalue())
                    documented.assert_not_called()

    def test_main_missing_source_and_output_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            missing = Path(tmp) / "missing"
            with mock.patch.object(guard, "REGISTER_TYPES", missing), \
                    contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(guard.main(["--html-dir", tmp]), 1)
            with contextlib.redirect_stderr(io.StringIO()) as error:
                self.assertEqual(guard.main(["--html-dir", str(missing)]), 1)
            self.assertIn("Doxygen HTML output not found", error.getvalue())

    def test_main_empty_output_fails(self):
        with tempfile.TemporaryDirectory() as tmp, contextlib.redirect_stderr(io.StringIO()) as error:
            self.assertEqual(guard.main(["--html-dir", tmp]), 1)
        self.assertIn("registered classes missing", error.getvalue())


class DocumentedPageTests(unittest.TestCase):
    def test_captured_title_and_original_freshness_boundary(self):
        with tempfile.TemporaryDirectory() as tmp:
            page = Path(tmp) / "classGaussianData.html"
            page.write_text(CAPTURED_CLASS_TITLE, encoding="utf-8")
            os.utime(page, (1000, 1000))
            self.assertEqual(guard.documented_classes(Path(tmp)), {"GaussianData"})
            self.assertEqual(guard.documented_classes(Path(tmp), 1000), {"GaussianData"})
            self.assertEqual(guard.documented_classes(Path(tmp), 1001), set())

    def test_corrupted_title_and_absent_class_page_do_not_count(self):
        with tempfile.TemporaryDirectory() as tmp:
            page = Path(tmp) / "classGaussianData.html"
            for title in (CAPTURED_CLASS_TITLE.replace("Class Reference", "File Reference"),
                          CAPTURED_CLASS_TITLE.replace("</title>", "</broken>")):
                with self.subTest(title=title):
                    page.write_text(title, encoding="utf-8")
                    self.assertEqual(guard.documented_classes(Path(tmp)), set())
            page.unlink()
            self.assertEqual(guard.documented_classes(Path(tmp)), set())

    def test_main_requires_the_actual_shipping_page_and_fresh_output(self):
        with tempfile.TemporaryDirectory() as tmp:
            directory = Path(tmp)
            source = directory / "register_types.cpp"
            source.write_text("GDREGISTER_CLASS(GaussianData);", encoding="utf-8")
            page = directory / "classGaussianData.html"
            page.write_text(CAPTURED_CLASS_TITLE, encoding="utf-8")
            os.utime(page, (1000, 1000))
            with mock.patch.object(guard, "REGISTER_TYPES", source), \
                    contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(guard.main(["--html-dir", tmp, "--newer-than", "1000"]), 0)
                self.assertEqual(guard.main(["--html-dir", tmp, "--newer-than", "1001"]), 1)
                page.unlink()
                self.assertEqual(guard.main(["--html-dir", tmp]), 1)


if __name__ == "__main__":
    unittest.main()
