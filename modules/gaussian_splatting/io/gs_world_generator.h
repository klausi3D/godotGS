// Synthetic test-world generator (BV-05; docs/architecture/adr-beyond-vram-worlds.md
// §6.1-§6.4, D-2, §4.1 sidecar manifest, W8).
//
// One seeded, counter-hash, re-iterable content definition for every tier:
//
//   - T0      4,194,304 splats, 512 x 512 m (controls, F/k sweep, identity, smoke);
//   - A       201,326,592 splats, 2,048 x 2,048 m, the exact §6.2 content table;
//   - A-mini  A's densities on 2 x 2 tiles (13,881,322 splats), for local evidence;
//   - T-smoke 262,144 splats on one tile, for unit tests;
//   - T-ref   not a tier of its own: a chunk subset of a tier (generate_world with a
//             selection), byte-identical to the parent's chunks.
//
// Content. A world is a grid of 256 m tiles over an open plain, with towns, one
// corridor of two walls, low-alpha foliage clusters and coded beacons (4 per tile).
// Every class count is exact: towns, walls and foliage are density x integer area,
// beacons a fixed splat count, and the plain is the remainder, apportioned to chunks
// by largest remainder over integer areas. The plan asserts the declared total.
//
// Chunks. 32 m cells aligned to the world origin (the HLOD lattice), subdivided by
// powers of two down to 8 m until a cell holds <= max_chunk_splats (65,536). Chunks are
// written in Morton order. Inside a chunk the splats are a stratified merge of the
// chunk's content parts (a prefix keeps every part's share) and each part is an
// additive-recurrence (R2) low-discrepancy sequence, so a prefix is a spatial sample.
//
// SH. Degree 3 from spatially correlated value-noise fields (4 latent channels,
// smoothstep-bilinear lattices at the correlation length and finer octaves); each
// coefficient is a fixed seeded mix of the latents plus a small per-splat jitter.
// sh.field_amp_q8 = 0 turns the field off (hash-noise SH), the negative control.
//
// Determinism. Every value is computed in integer or exact dyadic arithmetic: no libm
// call, no float division or square root on the per-splat path, and the only rounding
// is the final narrowing of a fixed-point position to float (toward negative infinity,
// so a splat never lands on its cell's upper edge). The bytes therefore do
// not depend on FMA contraction, fast-math reassociation or the compiler, and the
// pinned golden digests in the [WorldGenerator] doctests hold on every platform.
//
// Streaming. generate_world() drives gs_world_writer::Writer in REITERABLE mode: each
// pass regenerates the chunks one at a time (the writer refuses a pass 2 that diverges
// from pass 1, which makes it a determinism check too). RAM is the plan (features,
// chunk table, a few hundred kB for Tier A) plus one chunk buffer (<= 65,536 splats,
// about 19 MB); the world is never materialized (I-8).
//
// Manifest (§4.1, W8). After finalize() the file is read back sequentially and every
// per-chunk gaussian / SH digest and the file digest are recomputed from disk and
// compared with the digests taken from memory while generating. Only then is the
// sidecar <stem>.manifest.json written (atomically). It carries the parameters and
// generator_params_sha, gen_sha, writer and codec versions, the exact content table,
// every feature (towns, walls, foliage, beacons with their codes), and per chunk:
// cell, Morton key, counts per class, the chunk-table AABB/centre/radius, byte ranges
// and SHA-256 digests. The manifest holds no timing, so its bytes are deterministic too.
