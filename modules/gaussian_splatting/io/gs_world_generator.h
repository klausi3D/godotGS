	uint64_t file_bytes = 0;
	uint64_t splat_count = 0;
	uint32_t chunk_count = 0;
	uint64_t plan_usec = 0;
	uint64_t pass_usec[2] = {};
	uint64_t finalize_usec = 0;
	uint64_t verify_usec = 0;
