struct IRect {
	int64_t x0 = 0;
	int64_t z0 = 0;
	int64_t x1 = 0;
	int64_t z1 = 0;
	int64_t width() const { return x1 - x0; }
	int64_t depth() const { return z1 - z0; }
	int64_t area() const { return (x1 > x0 && z1 > z0) ? (x1 - x0) * (z1 - z0) : 0; }
	bool intersects(const IRect &p_o) const { return x0 < p_o.x1 && p_o.x0 < x1 && z0 < p_o.z1 && p_o.z0 < z1; }
	IRect intersection(const IRect &p_o) const;
	IRect grown(int64_t p_by) const { return IRect{ x0 - p_by, z0 - p_by, x1 + p_by, z1 + p_by }; }
};

struct Feature {
	ContentClass cls = CLASS_PLAIN;
	uint32_t index = 0; // index within its class
	IRect footprint; // towns, foliage: the content rect; walls: the excluded strip; beacons: the panel's x range x [z, z+1)
	int64_t count = 0;
	// Walls: the plane z and the x range. Beacons: the panel centre and the code.
	int64_t plane_z_m = 0;
	int64_t beacon_center_x_m = 0;
	int64_t beacon_center_z_m = 0;
	uint32_t beacon_id = 0;
	uint64_t beacon_code = 0;
};

struct ChunkPart {
	ContentClass cls = CLASS_PLAIN;
	uint32_t feature = UINT32_MAX; // index into Plan::features; UINT32_MAX for the plain
	IRect rect; // content rect within the cell (plain: the cell)
	uint32_t count = 0;
};

struct ChunkPlan {
	IRect cell;
	uint64_t morton = 0;
	uint32_t first_part = 0;
	uint32_t part_count = 0;
	uint32_t first_plain_rect = 0;
	uint32_t plain_rect_count = 0;
	int64_t plain_area = 0;
	uint32_t count = 0;
	uint32_t class_counts[CLASS_COUNT] = {};
};

struct Plan {
	Params params;
	IRect world;
	LocalVector<Feature> features;
	LocalVector<ChunkPlan> chunks; // Morton order
	LocalVector<ChunkPart> parts;
	LocalVector<IRect> plain_rects;
	uint64_t class_totals[CLASS_COUNT] = {};
	uint32_t class_instances[CLASS_COUNT] = {};
	int64_t plain_area = 0;
	uint64_t total_splats = 0;
	uint32_t max_chunk_count = 0;
	uint32_t sh_first_order = 0;
	uint32_t sh_high_order = 0;
	AABB world_bounds;
	// Seeded SH mixing weights [coefficient][latent], int8 range.
	LocalVector<int32_t> sh_weights;
	String params_sha;
};

