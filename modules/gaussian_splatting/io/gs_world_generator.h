enum ContentClass : uint8_t {
	CLASS_PLAIN = 0,
	CLASS_TOWN = 1,
	CLASS_WALL = 2,
	CLASS_FOLIAGE = 3,
	CLASS_BEACON = 4,
	CLASS_COUNT = 5,
};

const char *class_name(ContentClass p_class);

// Per-class appearance. sigma in 1/4096 m, opacity in 1/256, colour 0..255 (rendered
// colour, sh_dc = colour/256 - 0.5 under the LINEAR_RGB DC encoding).
struct ClassStyle {
	int64_t sigma_min_q = 0;
	int64_t sigma_max_q = 0;
	int64_t opacity_min_q8 = 0;
	int64_t opacity_max_q8 = 0;
	int64_t color_r = 0;
	int64_t color_g = 0;
	int64_t color_b = 0;
	int64_t color_var_q8 = 0; // latent-driven colour variation amplitude
};

// Every parameter is an integer (or a fixed string) so the canonical JSON, and with
// it generator_params_sha, is unambiguous. Units are in the names.
struct Params {
	String tier;
	int64_t seed = 0;

	int64_t tile_size_m = 256;
	int64_t tiles_x = 0;
	int64_t tiles_z = 0;
	int64_t base_cell_m = 32;
	int64_t min_cell_m = 8;
	int64_t max_chunk_splats = 65536;
	int64_t total_splats = 0;

	// Placement: features keep `margin_m` from each other and from reserved cells,
	// and `edge_margin_m` from the world edge.
	int64_t margin_m = 8;
	int64_t edge_margin_m = 16;

	int64_t plain_y_jitter_q = 512; // 1/4096 m
	int64_t ground_flatten_shift = 2; // sigma_y = sigma >> shift for ground splats

	int64_t town_count = 0;
	int64_t town_size_m = 40;
	int64_t town_block_m = 8;
	int64_t town_building_m = 6;
	int64_t town_height_min_m = 4;
	int64_t town_height_max_m = 20;
	int64_t town_density_per_m2 = 800;
	int64_t town_roof_permille = 250;

	int64_t wall_length_m = 0;
	int64_t wall_height_m = 4;
	int64_t wall_footprint_m = 6;
	int64_t wall_separation_m = 10;
	int64_t wall_density_per_m2 = 300;
	int64_t wall_corridor_z_m = 8;

	int64_t foliage_count = 0;
	int64_t foliage_size_m = 30;
	int64_t foliage_density_per_m2 = 200;
	int64_t foliage_canopy_min_q = 2048; // 1/4096 m
	int64_t foliage_canopy_max_q = 32768;

	int64_t beacon_grid = 64; // splats per panel side; beacon_grid^2 splats per beacon
	int64_t beacon_panel_m = 8;
	int64_t beacon_base_y_q = 2048;
	// Tile-local base-cell coordinates of the beacons, flattened (x0, z0, x1, z1, ...).
	LocalVector<int64_t> beacon_cells;

	int64_t sh_degree = 3;
	int64_t sh_corr_log2_m = 4; // correlation length 2^4 = 16 m
	int64_t sh_octaves = 2;
	int64_t sh_field_amp_q8 = 256; // 0 = no correlated field (hash-noise SH control)
	int64_t sh_jitter_amp = 1024;
	int64_t sh_band_shift_1 = 1;
	int64_t sh_band_shift_2 = 2;
	int64_t sh_band_shift_3 = 3;

	ClassStyle style[CLASS_COUNT];
};

