// sha256 over every chunk's gaussian and SH bytes in chunk order, without writing a
// file. The no-dead-parameter test and the golden digest use it.
Error compute_content_digest(const Params &p_params, String &r_hex, String &r_error);

struct GenerateOptions {
	// Chunk indices of the parent plan (sorted, unique). Empty = the whole world.
	// A selection makes a T-ref world: same content, only these chunks.
	LocalVector<uint32_t> selection;
	// ADR §6.1: a T-ref holds at most 12M splats.
	uint64_t max_selection_splats = 12000000u;
	// Compare every chunk digest recomputed from disk with the generated bytes. The
	// file digest is always computed from disk.
	bool verify_readback = true;
	bool print_progress = false;
};

