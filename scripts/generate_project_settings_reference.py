def _group(key: str) -> str:
    rest = key[len(SETTING_PREFIX):]
    return rest.split("/", 1)[0] if "/" in rest else "(top level)"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _html(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_registered_table(keys: list[str], by_key: dict[str, list[Registration]]) -> list[str]:
    rows = [
        "<table>",
        "  <thead>",
        "    <tr>",
        "      <th>Setting</th>",
        "      <th>Default (as registered)</th>",
        "      <th>Registered in</th>",
        "    </tr>",
        "  </thead>",
        "  <tbody>",
    ]
    for key in keys:
        registrations = by_key[key]
        files = sorted({r.file for r in registrations})
        rows.extend(
            [
                "    <tr>",
                f"      <td><pre><code>{key}</code></pre></td>",
                f"      <td><pre><code>{_html(registrations[0].default)}</code></pre></td>",
                f"      <td><pre><code>{'<br>'.join(files)}</code></pre></td>",
                "    </tr>",
            ]
        )
    rows.extend(["  </tbody>", "</table>"])
    return rows


def build_reference(manifest: dict, by_key: dict[str, list[Registration]], manual_block: list[str] | None = None) -> str:
    entries = manifest_entries(manifest)
    aliases = sorted(key for key, entry in entries.items() if _is_alias(entry))
    registered = sorted(key for key in entries if key in by_key)
    unregistered = sorted(key for key in entries if key not in by_key and key not in aliases)

    grouped: dict[str, list[str]] = defaultdict(list)
    for key in registered:
        grouped[_group(key)].append(key)
    group_order = sorted(grouped, key=lambda group: (group != "(top level)", group))

    # No "Last generated" timestamp: the output must be a pure function of the
    # manifest and the source, so CI can freshness-check it.
    sections: list[str] = ["# Project Settings Reference", ""]
    if manual_block:
        sections.extend(manual_block)
        sections.append("")
    sections.extend(
        [
            "## Purpose",
            "Every Gaussian Splatting project setting key, its registered default, and the source file that registers it.",
            "",
            "The key set comes from `modules/gaussian_splatting/config/project_settings_manifest.json`. The defaults and",
            "registering files come from the module source. Generation fails when the two disagree.",
            "A default is shown as the C++ expression passed at registration (for example a named constant), not as an evaluated value.",
            "",
            "## Usage",
            "| Task | Action |",
            "| --- | --- |",
            "| Regenerate this reference | Run `python3 scripts/generate_project_settings_reference.py`. |",
            "| Check this page covers the manifest | Run `python3 tests/ci/check_project_settings_reference.py`. |",
            "",
            "## API",
            "",
            "### Coverage",
            "",
            "| Coverage | Count |",
            "| --- | ---: |",
            f"| Keys in the manifest | {len(entries)} |",
            f"| Registered by the module at startup | {len(registered)} |",
            f"| Read by the module but not registered | {len(unregistered)} |",
            f"| Deprecated aliases (read only, never registered) | {len(aliases)} |",
            "",
            "### Registered keys",
            "Registered through `GLOBAL_DEF(...)`, `GLOBAL_DEF_RST(...)` or `ProjectSettings::set_initial_value(...)`, grouped by key prefix.",
            "",
        ]
    )
    for group in group_order:
        sections.extend([f"#### {group}", ""])
        sections.extend(render_registered_table(grouped[group], by_key))
        sections.append("")

    sections.extend(
        [
            "### Read but not registered",
            "Listed in the manifest and read by module code, but not registered: they do not appear in the editor's Project Settings until a project sets them.",
            "",
        ]
    )
    if unregistered:
        sections.extend(["| Setting | What it controls (manifest `effective_state`) |", "| --- | --- |"])
        for key in unregistered:
            sections.append(f"| `{key}` | {_cell(str(entries[key].get('effective_state', '-')))} |")
    else:
        sections.append("None.")
    sections.append("")

    sections.extend(
        [
            "### Deprecated aliases",
            "Old key spellings still read when a project sets them explicitly; see the [migration notes](gaussian-project-settings-migration.md).",
            "",
        ]
    )
    if aliases:
        sections.extend(["| Setting | Manifest note |", "| --- | --- |"])
        for key in aliases:
            sections.append(f"| `{key}` | {_cell(str(entries[key].get('notes', entries[key].get('effective_state', '-'))))} |")
    else:
        sections.append("None.")
    sections.append("")

    sections.extend(
        [
            "## Examples",
            "```bash",
            "python3 scripts/generate_project_settings_reference.py",
            "python3 tests/ci/check_project_settings_reference.py",
            "```",
            "",
            "## Troubleshooting",
            "| Issue | Cause | Fix |",
            "| --- | --- | --- |",
            "| Generation fails: key missing from the manifest | Code registers a key the manifest does not list. | Add the key to `project_settings_manifest.json` (the manifest guard requires it too), then regenerate. |",
            "| Generation fails: cannot resolve a key expression | A registration uses a key form the scanner does not understand. | Use a literal, a `const String`/`StringName` constant, a `#define`, or extend the scanner; never drop the registration from the page by hand. |",
            "| Generation fails: conflicting defaults | One key is registered in two places with different defaults. | Make the registrations agree. |",
            "| `check_project_settings_reference.py` fails | This page and the manifest list different keys. | Regenerate this file. |",
            "| `docs-build` reports this page stale | The manifest or a registration changed without regenerating. | Regenerate this file and commit it. |",
        ]
    )
    return "\n".join(sections)


def _source_referenced_keys() -> set[str]:
    """Keys the module source references at all, using the manifest guard's own
    definition (modules/gaussian_splatting/tests/check_project_settings_manifest.py)."""
    import importlib.util

    checker_path = MODULE_ROOT / "tests" / "check_project_settings_manifest.py"
    spec = importlib.util.spec_from_file_location("_gs_project_settings_manifest_check", checker_path)
    if spec is None or spec.loader is None:
        raise GenerationError(f"  - cannot load {checker_path}")
    checker = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(checker)
    return set(checker.collect_source_setting_paths())


def unreferenced_errors(manifest: dict, by_key: dict[str, list[Registration]], referenced: set[str]) -> list[str]:
    """A manifest key that is neither registered nor read cannot be listed as
    'read but not registered' without lying."""
    return [
        f"{key}: in the manifest, but the source neither registers nor reads it"
        for key, entry in sorted(manifest_entries(manifest).items())
        if key not in by_key and not _is_alias(entry) and key not in referenced
    ]


def generate() -> str:
    manifest = load_manifest()
    files = load_sources()
    registrations, errors = collect_registrations(files)
    by_key, model_errors = build_model(manifest, registrations)
    errors.extend(model_errors)
    errors.extend(unreferenced_errors(manifest, by_key, _source_referenced_keys()))
    if errors:
        raise GenerationError("\n".join(f"  - {error}" for error in errors))
    manual_block = extract_manual_block(OUTPUT.read_text(encoding="utf-8")) if OUTPUT.exists() else []
    return build_reference(manifest, by_key, manual_block) + "\n"


def main() -> int:
    try:
        content = generate()
    except GenerationError as exc:
        print("[docs] Project settings reference NOT written; manifest and source disagree:", file=sys.stderr)
        print(str(exc), file=sys.stderr)
        return 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # LF on every platform, so a Windows regeneration is byte-identical to CI's.
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(f"[docs] Wrote project settings reference to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
