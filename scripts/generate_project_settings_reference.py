#!/usr/bin/env python3
"""Generate the ProjectSettings reference for the Gaussian Splatting module.

Key set: `modules/gaussian_splatting/config/project_settings_manifest.json` is the
authority. Every manifest key appears on the page exactly once.

Registration facts (default value, registering file): a scan of the module's
production C++ for every registration form the code uses --
`GLOBAL_DEF*(key, default)` (key as a literal, a constant, a macro, a
`PropertyInfo(...)` second argument or a path-returning function, any number
of lines), `ProjectSettings::set_initial_value(key, default)`, and
helper functions that forward a `p_*` default parameter to `GLOBAL_DEF`.

Generation FAILS (exit 1, nothing written) instead of guessing when the two
sources disagree:
- a registration whose key expression cannot be resolved to a setting path;
- a registered key missing from the manifest;
- a manifest deprecated alias that the source registers;
- one key registered with two different default expressions;
- a manifest key (other than an alias) that the source neither registers nor
  reads, as judged by the manifest guard's own source scan.

Manifest keys that the source reads but never registers are listed in their
own table, so the page still covers every manifest key.
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "reference" / "project-settings.md"
MODULE_ROOT = ROOT / "modules" / "gaussian_splatting"
MANIFEST_PATH = MODULE_ROOT / "config" / "project_settings_manifest.json"
SETTING_PREFIX = "rendering/gaussian_splatting/"
SOURCE_SUFFIXES = {".cpp", ".h"}
# Same production-source definition as modules/gaussian_splatting/tests/check_project_settings_manifest.py.
SOURCE_EXCLUDE_PARTS = {"tests", "doc_classes"}
ALIAS_PUBLICNESS = {"deprecated_alias"}
ALIAS_SCOPES = {"migration_alias"}

# The reference file carries a hand-maintained blockquote region (manual
# annotations) between the header and the generated tables, terminated by this
# exact marker line. Regeneration MUST preserve that region verbatim; it is not
# reproducible from source. Everything after the marker is regenerated.
MANUAL_BLOCK_MARKER = (
    "> This block is hand-maintained. Everything below it is regenerated by"
    " `scripts/generate_project_settings_reference.py`."
)
# Earlier marker wording, still recognised so a regeneration over an older copy
# of the file keeps its hand-maintained block instead of silently dropping it.
LEGACY_MANUAL_BLOCK_MARKERS = (
    "> This block is hand-maintained. The rest of this file is regenerated by the script above.",
)


class GenerationError(Exception):
    """Manifest and source disagree, or the source cannot be resolved."""


def extract_manual_block(existing_text: str) -> list[str]:
    """Return the contiguous hand-maintained blockquote region (up to and
    including MANUAL_BLOCK_MARKER) from an existing reference file, or [] if the
    marker is absent (first generation)."""
    lines = existing_text.splitlines()
    markers = (MANUAL_BLOCK_MARKER, *LEGACY_MANUAL_BLOCK_MARKERS)
    marker_idx = next(
        (i for i, line in enumerate(lines) if line.strip() in markers),
        None,
    )
    if marker_idx is None:
        return []
    start = marker_idx
    while start - 1 >= 0 and lines[start - 1].startswith(">"):
        start -= 1
    # Always re-emit the current marker wording.
    return [*lines[start:marker_idx], MANUAL_BLOCK_MARKER]


